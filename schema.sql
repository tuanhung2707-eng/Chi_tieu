drop policy if exists "own budgets insert" on public.monthly_budgets;
create policy "own budgets insert" on public.monthly_budgets for insert to authenticated with check ((select auth.uid())=user_id);
drop policy if exists "own budgets update" on public.monthly_budgets;
create policy "own budgets update" on public.monthly_budgets for update to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
drop policy if exists "own budgets delete" on public.monthly_budgets;
create policy "own budgets delete" on public.monthly_budgets for delete to authenticated using ((select auth.uid())=user_id);
